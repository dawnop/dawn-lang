    T = name
    big = (w == 64)
    lo = -(1 << (w - 1)) if signed else 0
    hi = (1 << (w - 1)) - 1 if signed else (1 << w) - 1
    mask = (1 << w) - 1
    kind = "signed" if signed else "unsigned"
