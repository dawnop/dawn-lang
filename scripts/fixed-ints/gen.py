def rng(w, s):
    return (-(1 << (w-1)), (1 << (w-1)) - 1) if s else (0, (1 << w) - 1)

def wrap(v, w, s):
    v &= (1 << w) - 1
    if s and v >= 1 << (w-1):
        v -= 1 << w
    return v

def tdiv(a, b):  # truncating, as Int's / (operands here never overflow Int)
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q

def trem(a, b):
    return a - tdiv(a, b) * b

def pairs(w, s):
    lo, hi = rng(w, s)
    ps = [(hi, 1), (lo, 1), (lo, hi), (hi, hi), (7, 3), (100, 7)]
    if s:
        ps += [(lo, -1), (-7, 3), (7, -3), (-7, -3), (-1, hi)]
    else:
        ps += [(hi, 2), (hi - 5, hi), (1, hi), (hi // 2 + 3, 2)]
    out = []
    for a, b in ps:
        a = max(lo, min(hi, a)); b = max(lo, min(hi, b))
        if b != 0:
            out.append((a, b))
    return out

def lit(v, name, w, s):
    """A Dawn expression of type T with value v."""
    m = name.lower()
    if w == 64 and v > (1 << 63) - 1:
        return f"{m}.wrap({v - (1 << 64)})"
    return f"{m}_({v})"

def show(v):
    return str(v)

def checked(v, w, s):
    lo, hi = rng(w, s)
    return f"Some({v})" if lo <= v <= hi else "None"

