#!/usr/bin/env python3
"""Embed optional compiler diagnostics without a runtime javac dependency."""
import argparse
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'runtime/jvm/AsmDiagnostics.java'
OUTPUT = ROOT / 'selfhost/src/embed/asm_diagnostics_rt.dawn'

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--javac', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix='asm-diagnostics-') as directory:
        work = Path(directory)
        subprocess.run([str(args.javac), '--release', '8', '-g:none', '-d', str(work), str(SOURCE)], check=True)
        rows = ['# Generated by scripts/gen-asm-diagnostics.py; do not edit.',
                '# Diagnostics are carried only by programs that use ASM.',
                'use std/bytes', '', 'pub fn classes() -> List[(String, Bytes)] = [']
        for file in sorted((work / 'dawn/rt').glob('AsmDiagnostics*.class')):
            name = 'dawn/rt/' + file.stem.replace('$', '\\$')
            rows.append('  ("' + name + '", bytes.from_hex("' + file.read_bytes().hex() + '").expect("ASM diagnostics class")),')
        result = '\n'.join(rows + [']', ''])
        if args.check:
            if not OUTPUT.exists() or OUTPUT.read_text() != result: raise SystemExit('stale embedded ASM diagnostics')
        else: OUTPUT.write_text(result)

if __name__ == '__main__': main()
