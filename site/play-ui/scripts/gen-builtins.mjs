// Turn `dawn doc --builtins` output into a typed completion table baked into the
// bundle. Run by prebuild/predev. Reads site/build/builtins.json when present
// (build.sh produces it first); falls back to regenerating it via the dawn CLI
// so `npm run dev` works standalone.
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '../../..')
const buildJson = resolve(repoRoot, 'site/build/builtins.json')
const outFile = resolve(here, '../src/builtins.generated.ts')

function loadBuiltins() {
  if (existsSync(buildJson)) return JSON.parse(readFileSync(buildJson, 'utf8'))
  const raw = execFileSync(resolve(repoRoot, 'bin/dawn'), ['doc', '--builtins'], {
    encoding: 'utf8',
    maxBuffer: 8 * 1024 * 1024,
  })
  return JSON.parse(raw)
}

// `data.groups` and nothing else. `data.internal` is the std-only half of the
// builtin table -- the backend contracts behind std/map, std/bytes, std/io and
// the rest -- which the checker refuses outside std, so offering any of it in
// the playground's completion would be offering a compile error.
//
// The same rule splits what is left. A prelude group (`io`, `list`, ...) is in
// scope everywhere, so its functions complete under their bare names. A module
// group (`std/str`, ...) is not: its functions are only reachable as
// `str.trim` after `use std/str`, so they carry `module` and the editor offers
// them qualified (and adds the `use`). Emitting them bare, as this script once
// did for all 440 entries, offered `trim(...)`, which does not compile.
//
// Module docs keep their first paragraph only. The table is baked into the
// bundle and was its largest input after @codemirror/view; the full text is
// one hover away in the LSP and on the stdlib page, and the first paragraph is
// what a completion tooltip has room for.
const data = loadBuiltins()
const fns = []
for (const group of data.groups ?? []) {
  const isModule = group.name.startsWith('std/')
  for (const fn of group.fns ?? []) {
    const doc = fn.doc ?? ''
    const entry = {
      name: fn.name,
      sig: fn.sig,
      doc: isModule ? doc.split(/\n\s*\n/)[0] : doc,
      group: group.name,
    }
    if (isModule) entry.module = group.name
    fns.push(entry)
  }
}
fns.sort((a, b) => a.name.localeCompare(b.name) || a.group.localeCompare(b.group))

const banner = `// GENERATED by scripts/gen-builtins.mjs from \`dawn doc --builtins\`. Do not edit.\n`
const body =
  `// \`module\` is set on a function only reachable through \`use <module>\`.\n` +
  `export interface Builtin { name: string; sig: string; doc: string; group: string; module?: string }\n` +
  `export const BUILTINS: Builtin[] = [\n${fns.map((f) => JSON.stringify(f)).join(',\n')},\n]\n`

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, banner + body)
const modular = fns.filter((f) => f.module).length
console.log(`gen-builtins: wrote ${fns.length} builtins (${fns.length - modular} prelude, ${modular} module) to ${outFile}`)
