#!/usr/bin/env python3
"""Embed an optional JVM runtime without invoking javac in emitted programs.

The checked-in payload is built with the pinned JDK 21, release 8, and no
build paths or debug attributes. Compiler implementation remains seed syntax.
"""
import argparse
import hashlib
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT/'runtime/jvm/Provenance.java'
OUTPUT = ROOT/'selfhost/src/embed/provenance_rt.dawn'


def write_runtime_stubs(work):
    """Compile against the same erased tuple/array ABI the backend emits."""
    files = []
    poison = work/'CtlDiscard.java'
    poison.write_text('package dawn.rt; public final class CtlDiscard extends Error { public CtlDiscard() {} }\n')
    files.append(poison)
    for arity in [2, 3, 4, 5, 6]:
        file = work/f'Tuple{arity}.java'
        fields = ' '.join(f'public final Object _{i};' for i in range(arity))
        params = ', '.join(f'Object a{i}' for i in range(arity))
        assignments = ' '.join(f'_{i}=a{i};' for i in range(arity))
        file.write_text(f'package dawn.rt; public final class Tuple{arity} {{ {fields} public Tuple{arity}({params}) {{ {assignments} }} }}\n')
        files.append(file)
    file = work/'Array.java'
    file.write_text('package dawn.rt; public final class Array { private final Object[] data; private Array(Object[] a,int n) { data=java.util.Arrays.copyOf(a,n); } public static Array array_wrap(Object[] a,int n) { return new Array(a,n); } public static Object array_get(Array a,long i) { return a.data[(int)i]; } public static long array_len(Array a) { return a.data.length; } }\n')
    files.append(file)
    return files

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--javac', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix='provenance-classes-') as directory:
        work = Path(directory)
        stub = work/'PanicError.java'
        stub.write_text('package dawn.rt; public final class PanicError extends Error { public PanicError(String message) { super(message); } }\n')
        fn_stubs = []
        for arity in range(1, 10):
            stub_file = work/f'Fn{arity}.java'
            parameters = ', '.join(f'Object a{i}' for i in range(arity))
            stub_file.write_text(f'package dawn.rt; public interface Fn{arity} {{ Object apply({parameters}); Object applyObserved({parameters}, long context); }}\n')
            fn_stubs.append(stub_file)
        subprocess.run([str(args.javac), '--release', '8', '-Xlint:-options', '-g:none', '-d', str(work), str(stub), *(str(f) for f in fn_stubs), *(str(f) for f in write_runtime_stubs(work)), str(SOURCE)], check=True)
        rows = ['# Generated by scripts/gen-provenance-rt.py; do not edit.',
                '# Optional class payloads keep observation out of U0 artifacts.',
                'use std/bytes', '',
                'pub fn source() -> String = "' + SOURCE.read_text().replace('\\','\\\\').replace('"','\\"').replace('$','\\$').replace('\n','\\n') + '"', '',
                'pub fn classes() -> List[(String, Bytes)] = [']
        for file in sorted((work/'dawn/rt').glob('Provenance*.class')):
            name = 'dawn/rt/'+file.stem.replace('$','\\$')
            rows.append('  ("'+name+'", bytes.from_hex("'+file.read_bytes().hex()+'").expect("provenance class")),')
        rows += [']', '']
        result = '\n'.join(rows)
        if args.check:
            if not OUTPUT.exists() or OUTPUT.read_text() != result:
                raise SystemExit('stale embedded provenance runtime')
        else:
            OUTPUT.write_text(result)
            print('Wrote optional provenance classes; source SHA-256 '+hashlib.sha256(SOURCE.read_bytes()).hexdigest())


if __name__ == '__main__':
    main()
