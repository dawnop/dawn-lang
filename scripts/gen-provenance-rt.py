#!/usr/bin/env python3
"""Embed an optional JVM runtime without invoking javac in emitted programs.

The checked-in payload is built with the pinned JDK 21, release 8, and no
build paths or debug attributes. Compiler implementation remains seed syntax.
"""
import argparse
import hashlib
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT/'runtime/jvm/Provenance.java'
OUTPUT = ROOT/'selfhost/src/embed/provenance_rt.dawn'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--javac', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix='provenance-classes-') as directory:
        work = Path(directory)
        stub = work/'PanicError.java'
        stub.write_text('package dawn.rt; public final class PanicError extends Error { public PanicError(String message) { super(message); } }\n')
        fn_stubs = []
        for arity in [1, 2]:
            stub_file = work/f'Fn{arity}.java'
            parameters = ', '.join(f'Object a{i}' for i in range(arity))
            stub_file.write_text(f'package dawn.rt; public interface Fn{arity} {{ Object apply({parameters}); Object applyObserved({parameters}, long context); }}\n')
            fn_stubs.append(stub_file)
        subprocess.run([str(args.javac), '--release', '8', '-Xlint:-options', '-g:none', '-d', str(work), str(stub), *(str(f) for f in fn_stubs), str(SOURCE)], check=True)
        rows = ['# Generated by scripts/gen-provenance-rt.py; do not edit.',
                '# Optional class payloads keep observation out of U0 artifacts.',
                'use std/bytes', '',
                'pub fn source() -> String = "' + SOURCE.read_text().replace('\\','\\\\').replace('"','\\"').replace('$','\\$').replace('\n','\\n') + '"', '',
                'pub fn classes() -> List[(String, Bytes)] = [']
        for file in sorted((work/'dawn/rt').glob('Provenance*.class')):
            name = 'dawn/rt/'+file.stem.replace('$','\\$')
            rows.append('  ("'+name+'", bytes.from_hex("'+file.read_bytes().hex()+'").expect("provenance class")),')
        rows += [']', '']
        result = '\n'.join(rows)
        if args.check:
            if not OUTPUT.exists() or OUTPUT.read_text() != result:
                raise SystemExit('stale embedded provenance runtime')
        else:
            OUTPUT.write_text(result)
            print('Wrote optional provenance classes; source SHA-256 '+hashlib.sha256(SOURCE.read_bytes()).hexdigest())


if __name__ == '__main__':
    main()
